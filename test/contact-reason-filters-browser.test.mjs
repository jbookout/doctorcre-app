import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {chromium, settles, pausedClock} from './browser-harness.mjs';
import {routeLeads} from './leads-browser-fixture.mjs';
import {practiceOriginationFixture} from '../data/fixtures/practice-origination.mjs';

for (const width of [1280,390]) for (const theme of ['light','dark']) test(`loaded reason filters at ${width}px ${theme}`, async t => {
  const browser = await chromium.launch();
  t.after(() => browser.close());
  const page = await browser.newPage({viewport:{width,height:1000},reducedMotion:'reduce'});
  await page.addInitScript(theme => localStorage.setItem('doctorcre.visual-preferences',JSON.stringify({theme,walkthroughSeen:{joe:true,dell:true,'example-partner':true}})),theme);
  await pausedClock(page,new Date('2026-10-30T12:00:00Z'));
  const reads = [], writes = [], errors = [];
  let payload = {...practiceOriginationFixture(),cards:[],next_cursor:null};
  page.on('pageerror',error => errors.push(error.message));
  await routeLeads(page,{getReasons:args => { reads.push(args); return args.before_id ? {...payload,cards:[{...payload.cards[0],id:'99',name:'Demo Later Practice'}],next_cursor:null} : payload; },onWrite:p => writes.push(p)});
  await page.goto('http://localhost/leads');
  const reasons = page.locator('#contactReasons');
  await settles(async () => assert.match(await reasons.innerText(),/No new reasons to reach out\./));
  assert.equal(await reasons.getByRole('searchbox').count(),0);
  await mkdir('.github/pr-evidence/WR39.S1.J5',{recursive:true});
  await reasons.screenshot({path:`.github/pr-evidence/WR39.S1.J5/empty-${width}-${theme}.png`});
  payload = {...practiceOriginationFixture(),next_cursor:'1'};
  reads.length = 0;
  await page.reload();
  await reasons.locator('.work-card').first().waitFor();
  assert.equal(await reasons.getByRole('searchbox',{name:'Search loaded reasons'}).count(),1);
  const search = reasons.getByRole('searchbox',{name:'Search loaded reasons'});
  const category = reasons.getByRole('combobox',{name:'Action category'});
  assert.equal(await category.count(),1);
  assert.equal(reads.length,1);
  assert.equal(reads[0].limit,25);
  const initial = width === 390 ? 1 : 2;
  assert.equal(await reasons.locator('.work-card').count(),initial);
  await search.fill('  demo group  ');
  assert.match(await reasons.innerText(),/1 matching loaded reasons/);
  assert.equal(await reasons.locator('h3').innerText(),'Demo Group Practice');
  await search.fill('Demo City');
  assert.match(await reasons.innerText(),/6 matching loaded reasons/);
  await search.fill('fl');
  assert.match(await reasons.innerText(),/6 matching loaded reasons/);
  await search.fill('2026-10');
  assert.equal(await reasons.locator('.work-card').count(),0);
  await search.fill('DEMO-CLIENT');
  assert.equal(await reasons.locator('h3').innerText(),'Follow up with DEMO-CLIENT');
  await category.selectOption('research');
  assert.equal(await reasons.locator('.work-card').count(),0);
  await category.selectOption('');
  await search.fill('');
  for (const [route,title,count] of [
    ['research','Demo New Practice',4],
    ['relationship_follow_up','Follow up with DEMO-CLIENT',1],
    ['identity_review','Demo Similar Practice',1],
  ]) {
    await category.selectOption(route);
    assert.match(await reasons.innerText(),new RegExp(`${count} matching loaded reasons`));
    assert.equal(await reasons.locator('h3').first().innerText(),title);
  }
  await search.fill('not a loaded practice');
  assert.equal(await reasons.locator('.work-card').count(),0);
  assert.match(await reasons.innerText(),/No matches among loaded reasons/);
  assert.doesNotMatch(await reasons.innerText(),/No new reasons/);
  assert.match(await reasons.innerText(),/Registry and publication dates do not confirm/);
  assert.match(await reasons.getByRole('list',{name:'Source coverage'}).innerText(),/Florida formations · Not yet covered/);
  assert.equal(await reasons.getByRole('button',{name:'More reasons',exact:true}).isEnabled(),true);
  await mkdir('.github/pr-evidence/WR39.S1.J5',{recursive:true});
  await reasons.screenshot({path:`.github/pr-evidence/WR39.S1.J5/zero-${width}-${theme}.png`});
  assert.equal(reads.length,1);
  assert.deepEqual(writes,[]);
  await reasons.getByRole('button',{name:'Clear',exact:true}).click();
  assert.equal(await reasons.locator('.work-card').count(),initial);
  assert.equal(await search.inputValue(),'');
  assert.equal(await category.inputValue(),'');
  await search.focus();
  await page.keyboard.type('group');
  assert.equal(await search.evaluate(node => node === document.activeElement),true);
  await page.keyboard.press('Tab');
  assert.equal(await category.evaluate(node => node === document.activeElement),true);
  await page.keyboard.press('Tab');
  await page.keyboard.press('Enter');
  assert.equal(await search.inputValue(),'');
  await reasons.getByRole('button',{name:/^Show/}).click();
  assert.equal(await reasons.locator('.work-card').count(),6);
  await search.fill('missing');
  await reasons.getByRole('button',{name:'More reasons',exact:true}).click();
  await settles(() => assert.equal(reads.length,2));
  await settles(async () => assert.equal(await reasons.getByRole('button',{name:'More reasons',exact:true}).count(),0));
  assert.equal(reads[1].before_id,'1');
  await reasons.getByRole('button',{name:'Clear',exact:true}).click();
  assert.equal(await reasons.locator('.work-card').count(),7);
  await search.fill('later');
  assert.equal(await reasons.locator('h3').innerText(),'Demo Later Practice');
  await reasons.getByRole('button',{name:'Clear',exact:true}).click();
  payload = {...payload,cards:[{...payload.cards[0],name:'Demo Long Practice Name for an Independently Operated Synthetic Regional Medical Group',city:'Demo Long City Name',state:'AL'}]};
  await search.fill('Long Practice');
  await search.focus();
  await page.clock.fastForward(60_001);
  await settles(async () => assert.equal(await reasons.locator('h3').innerText(),payload.cards[0].name));
  assert.equal(reads.length,3);
  assert.equal(await search.inputValue(),'Long Practice');
  assert.equal(await search.evaluate(node => node === document.activeElement),true);
  await mkdir('.github/pr-evidence/WR39.S1.J5',{recursive:true});
  await reasons.screenshot({path:`.github/pr-evidence/WR39.S1.J5/reasons-${width}-${theme}.png`});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  payload = {...payload,cards:[]};
  await page.clock.fastForward(60_001);
  await settles(async () => assert.match(await reasons.innerText(),/0 matching loaded reasons/));
  assert.match(await reasons.innerText(),/No matches among loaded reasons/);
  assert.equal(await reasons.getByRole('list',{name:'Source coverage'}).count(),1);
  await reasons.getByRole('button',{name:'Clear',exact:true}).click();
  assert.match(await reasons.innerText(),/None on this page\. Load more reasons below\./);
  assert.equal(await search.evaluate(node => node === document.activeElement),true);
  await page.evaluate(() => window.dispatchEvent(new Event('doctorcre-session-invalidated')));
  assert.match(await reasons.innerText(),/Sign in to view contact reasons/);
  assert.equal(await reasons.getByRole('searchbox').count(),0);
  assert.equal(await reasons.locator('.work-card').count(),0);
  assert.deepEqual(writes,[]);
  assert.deepEqual(errors,[]);
});
