import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { chromium } from './browser-harness.mjs';
import { ownedServer as startFixtureServer } from "./fixture-probe.ts";
import { directoryFixture } from './fixtures/vendor-directory.synthetic.mjs';
import { validateQuietFollowUps } from '../js/leads-client.js';
const meetingRecordings = JSON.parse(readFileSync(new URL('./fixtures/vendor-meetings/recordings.json', import.meta.url)));
const recorded = () => JSON.parse(readFileSync(new URL('./fixtures/quiet-vendor-owner-filter/recordings.json', import.meta.url))).response;

for (const width of [390,1280]) for (const theme of ['light','dark']) test(`loaded owner selection ${width} ${theme}`, async t => {
  const server=await startFixtureServer();t.after(()=>server.stop());
  const browser=await chromium.launch();t.after(()=>browser.close());
  const page=await browser.newPage({viewport:{width,height:900}});page.setDefaultTimeout(5000);
  await page.addInitScript(theme=>localStorage.setItem('doctorcre.visual-preferences',JSON.stringify({theme})),theme);
  let response=validateQuietFollowUps(recorded()),reads=0,denied=false;
  await page.route('https://**',route=>route.abort());
  await page.route('**/api/v1/business/**',route=>route.fulfill({json:directoryFixture(route.request().url())}));
  await page.route('**/mcp',route=>{
    const request=route.request().postDataJSON();
    const quiet=request.params.name==='quiet-follow-ups';
    if(quiet) reads++;
    const payload=quiet?(denied?{error:'forbidden'}:response):meetingRecordings[request.params.arguments.view];
    return route.fulfill({json:{jsonrpc:'2.0',id:request.id,result:{isError:quiet&&denied,content:[{type:'text',text:JSON.stringify(payload)}]}}});
  });
  await page.goto(server.url+'/vendors');
  const section=page.getByRole('region',{name:'Quiet vendor follow-ups'});
  await page.getByRole('button',{name:'Show quiet vendors'}).click();
  const select=section.getByRole('combobox',{name:'Quiet vendor owner'});
  await select.waitFor({timeout:2000});
  assert.ok((await select.boundingBox()).height >= 44, 'Owner selector uses the existing touch control size');
  assert.deepEqual(await select.locator('option').allTextContents(),['All owners','Joe','Dell','outside:all','Owner not recorded']);
  await section.getByRole('button',{name:'Next vendors'}).click();
  await select.focus();await page.keyboard.press('j');await page.keyboard.press('Enter');
  await section.getByText('Showing 1–5 of 7 matching loaded vendors.').waitFor();
  assert.equal(await select.inputValue(),'owner:joe');
  assert.equal(await section.getByRole('link').count(),5);
  await section.getByRole('button',{name:'Next vendors'}).click();
  await section.getByText('Showing 6–7 of 7 matching loaded vendors.').waitFor();
  await section.getByRole('button',{name:'Hide quiet vendors'}).click();
  await page.getByRole('button',{name:'Show quiet vendors'}).click();
  assert.equal(await select.inputValue(),'owner:joe');assert.equal(reads,1);
  await section.getByRole('button',{name:'Refresh quiet vendors'}).click();
  await select.waitFor();assert.equal(await select.inputValue(),'owner:joe');
  await select.selectOption('missing');
  assert.equal(await section.getByRole('link').count(),3);
  await select.selectOption('owner:outside:all');assert.equal(await section.getByRole('link').count(),1);
  await select.selectOption('all');assert.equal(reads,2);
  await select.selectOption('owner:joe');
  response={...recorded(),proposals:recorded().proposals.filter(row=>row.owner!=='joe')};
  await section.getByRole('button',{name:'Refresh quiet vendors'}).click();
  await section.getByText('The selected owner is no longer in this snapshot. Showing all owners.').waitFor();
  assert.equal(await select.inputValue(),'all');
  assert.equal(await section.evaluate(el=>el.scrollWidth<=el.clientWidth),true);
  denied=true;await section.getByRole('button',{name:'Refresh quiet vendors'}).click();await section.getByRole('alert').waitFor();
  assert.equal(await section.getByRole('link').count(),0);
  denied=false;response={...recorded(),proposals:[]};
  await section.getByRole('button',{name:'Refresh quiet vendors'}).click();await section.getByText('No quiet vendors in this server snapshot.').waitFor();
  response=recorded();response.proposals[0].owner={slug:'joe'};
  await section.getByRole('button',{name:'Refresh quiet vendors'}).click();await section.getByRole('alert').waitFor();
  response=recorded();delete response.proposals[14].owner;
  await section.getByRole('button',{name:'Refresh quiet vendors'}).click();await select.waitFor();
  await select.selectOption('missing');assert.equal(await section.getByRole('link').count(),3);
  await page.evaluate(async snapshot=>{
    const {mountQuietVendors}=await import('/js/ui-quiet-vendors.js');
    const host=document.createElement('div');document.body.append(host);
    let finish;const pending=new Promise(resolve=>finish=resolve);
    const view=mountQuietVendors(host,{load:()=>pending,href:()=>'/vendors',open:()=>{}});
    host.querySelector('button').click();view.dispose();finish(snapshot);
    await new Promise(resolve=>setTimeout(resolve,0));
    if(host.childElementCount!==0) throw Error('Disposed mount republished stale completion');
    host.remove();
  },recorded());
  await page.evaluate(()=>window.dispatchEvent(new Event('doctorcre-session-invalidated')));
  assert.equal(await section.count(),0);
});
