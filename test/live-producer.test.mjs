import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdir, writeFile, symlink, realpath } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { temporaryDirectory } from '../scripts/temp-directory.mjs';
import { verifyLiveProducer, linkLiveProducer } from '../scripts/live-producer.mjs';

test('live package binds the resolved module to the exact clean producer revision', async t => {
  const root = temporaryDirectory('live-package-', t);
  const git = args => execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
  git(['init', '-q']);
  await mkdir(root + '/mcp-server/test/helpers', { recursive: true });
  const entry = root + '/mcp-server/test/helpers/local-carr.mjs';
  await writeFile(entry, 'export const startLocalCarr = () => {};');
  git(['add', 'mcp-server/test/helpers/local-carr.mjs']);
  git(['-c', 'user.name=Test', '-c', 'user.email=test@example.invalid', 'commit', '-qm', 'synthetic producer']);
  const producer = { repository: 'DoctorCRE/carr-system', source_commit: git(['rev-parse', 'HEAD']) };
  await verifyLiveProducer(root, pathToFileURL(entry).href, producer);
  const app = temporaryDirectory('live-consumer-', t);
  await linkLiveProducer({ root: app, checkout: root, producer });
  await linkLiveProducer({ root: app, checkout: root, producer });
  assert.equal(await realpath(app + '/node_modules/mcp-server'), await realpath(root + '/mcp-server'));
  const otherApp = temporaryDirectory('live-wrong-package-', t);
  await mkdir(otherApp + '/node_modules');
  await symlink(app, otherApp + '/node_modules/mcp-server', 'dir');
  await assert.rejects(linkLiveProducer({ root: otherApp, checkout: root, producer }), /existing CARR package/);
  assert.equal(await realpath(otherApp + '/node_modules/mcp-server'), await realpath(app));
  await assert.rejects(verifyLiveProducer(root, pathToFileURL(entry).href, { ...producer, source_commit: '1'.repeat(40) }), /producer pin/);
  await assert.rejects(verifyLiveProducer(root, pathToFileURL(entry).href, { ...producer, repository: 'unrelated/repository' }));
  const other = root + '/other.mjs';
  await writeFile(other, 'export const startLocalCarr = () => {};');
  await assert.rejects(verifyLiveProducer(root, pathToFileURL(other).href, producer), /declared producer checkout/);
  await writeFile(entry, 'export const startLocalCarr = unknown;');
  await assert.rejects(verifyLiveProducer(root, pathToFileURL(entry).href, producer));
});
