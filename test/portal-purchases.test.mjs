import test from 'node:test';
import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { readFile } from 'node:fs/promises';
const output = await build({ entryPoints: ['src/ui/portal/purchases-state.ts'], bundle: true, write: false, platform: 'node', format: 'esm' });
const { purchaseTransition, initialPurchaseState, visibleProperties } = await import(`data:text/javascript;base64,${Buffer.from(output.outputFiles[0].contents).toString('base64')}`);
const fixture = JSON.parse(await readFile('test/fixtures/portal-purchases/example-health.market-study.json'));
test('twenty properties filter by immutable ID rather than option number', () => {
  const properties = Array.from({ length: 20 }, (_, index) => ({ ...fixture.properties[0], id: `capacity-${index}`, number: 20 - index, address: `Capacity ${index}` }));
  let state = purchaseTransition(properties, initialPurchaseState, { kind: 'filter', query: 'Capacity 19' });
  assert.deepEqual(visibleProperties(properties, state).map(p => p.id), ['capacity-19']);
  state = purchaseTransition(properties, state, { kind: 'select', id: 'capacity-19' });
  assert.equal(state.selected, 'capacity-19');
  assert.equal(properties.find(p => p.id === state.selected).number, 1);
});
test('selection and filter transitions preserve package identity and exclude context proposals', () => {
  const properties = fixture.properties;
  let state = initialPurchaseState;
  state = purchaseTransition(properties, state, { kind: 'select', id: 'sample-property-1' });
  assert.equal(state.selected, 'sample-property-1');
  state = purchaseTransition(properties, state, { kind: 'toggle', id: 'sample-property-1' });
  assert.deepEqual(state.proposed, ['sample-property-1']);
  state = purchaseTransition(properties, state, { kind: 'toggle', id: 'sample-property-2' });
  assert.deepEqual(state.proposed, ['sample-property-1']);
  state = purchaseTransition(properties, state, { kind: 'filter', query: 'Example Road' });
  assert.equal(state.selected, null);
  assert.deepEqual(visibleProperties(properties, state).map(p => p.id), ['sample-property-2']);
  assert.equal(purchaseTransition(properties, state, { kind: 'select', id: 'sample-property-1' }).selected, null);
  state = purchaseTransition(properties, state, { kind: 'reset' });
  assert.equal(visibleProperties(properties, state).length, 2);
  assert.deepEqual(state.proposed, ['sample-property-1']);
  state = purchaseTransition(properties, state, { kind: 'select', id: 'sample-property-2' });
  assert.equal(state.selected, 'sample-property-2');
  state = purchaseTransition(properties, state, { kind: 'close' });
  assert.equal(state.selected, null);
  state = purchaseTransition(properties, state, { kind: 'toggle', id: 'sample-property-1' });
  assert.deepEqual(state.proposed, []);
  assert.equal(purchaseTransition(properties, state, { kind: 'select', id: 'unknown' }).selected, null);
});
