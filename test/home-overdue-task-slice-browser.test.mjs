import test, { before, after } from 'node:test';
import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { mkdtemp, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium, fixtureServer } from './browser-harness.mjs';
import { overdueFixture } from '../scripts/prove-home-overdue-task-slice.mjs';
let root;
before(async () => {
  root = await mkdtemp(join(tmpdir(), 'overdue-browser-'));
  await build({ stdin: { contents: `import React from 'react'; import {createRoot} from 'react-dom/client'; import {HomeSections} from './src/ui/home/sections'; import {parseSnapshot} from './src/ui/home/inbox'; const root=createRoot(document.getElementById('root')); window.render=(snapshot,extra={})=>root.render(React.createElement(HomeSections,{items:parseSnapshot(snapshot).items,current:undefined,...extra,row:item=>React.createElement('p',{'data-id':item.item_id},item.title)})); window.dispose=()=>root.unmount();`, resolveDir: process.cwd(), loader: 'tsx' }, bundle: true, jsx: 'automatic', format: 'esm', outfile: join(root, 'test.js') });
  await writeFile(join(root, 'overdue-test.html'), '<div id="root"></div><script type="module" src="/test.js"></script>');
});
after(async () => rm(root, { recursive: true, force: true }));
for (const width of [390, 1440]) for (const theme of ['light', 'dark']) test(`overdue placement disclosure refresh and cleanup ${width} ${theme}`, async t => {
  const server = await fixtureServer({ root }); t.after(() => server.close());
  const browser = await chromium.launch(); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width, height: 900 }, colorScheme: theme });
  await page.clock.install({ time: new Date('2026-11-05T16:00:00Z') });
  await page.goto(`${server.origin}/overdue-test.html`);
  await page.waitForFunction(() => window.render);
  const snapshot = overdueFixture();
  await page.evaluate(snapshot => window.render(snapshot), snapshot);
  const overdue = page.getByRole('region', { name: 'Overdue', exact: true });
  await page.getByRole('region', { name: 'Today', exact: true }).waitFor();
  assert.equal(await overdue.count(), 1);
  assert.equal(await overdue.locator('[data-id]').count(), 1);
  await overdue.getByRole('button', { name: 'See all 2' }).click();
  assert.deepEqual(await overdue.locator('[data-id]').evaluateAll(nodes => nodes.map(n => n.dataset.id)), ['overdue-task', 'overdue-call']);
  for (const name of ['Needs your attention', 'Today']) assert.equal(await page.getByRole('region', { name, exact: true }).locator('[data-id^="overdue-"]').count(), 0);
  assert.deepEqual(await page.locator('section').evaluateAll(nodes => nodes.slice(0, 3).map(n => n.getAttribute('aria-label'))), ['Overdue', 'Needs your attention', 'Today']);
  const attention = page.getByRole('region', { name: 'Needs your attention', exact: true });
  await attention.getByRole('button', { name: 'See all 4' }).click();
  assert.deepEqual(await attention.locator('[data-id]').evaluateAll(nodes => nodes.map(n => n.dataset.id)), ['future-task', 'undated-task', 'failed-task', 'non-action']);
  assert.equal(await page.getByRole('region', { name: 'Today', exact: true }).locator('[data-id]').getAttribute('data-id'), 'today-task');
  const invalid = structuredClone(snapshot); invalid.items[0].due_on = '2026-02-31';
  await assert.rejects(page.evaluate(invalid => window.render(invalid), invalid), /unreadable card context/);
  await overdue.getByRole('button', { name: 'Show less' }).click();
  await page.evaluate(snapshot => window.render(snapshot, { current: 'overdue-call' }), snapshot);
  await page.waitForFunction(() => document.querySelectorAll('[aria-label="Overdue"] [data-id]').length === 2);
  const changed = structuredClone(snapshot); changed.items[0].due_on = '2026-11-06';
  await page.evaluate(({ snapshot, changed }) => window.render(changed, { pinned: snapshot.items[0] }), { snapshot, changed });
  await overdue.locator('[data-id="overdue-task"]').waitFor();
  await page.evaluate(changed => window.render(changed), changed);
  await overdue.locator('[data-id="overdue-task"]').waitFor({ state: 'detached' });
  await page.evaluate(snapshot => window.render(snapshot), snapshot);
  await overdue.getByRole('button', { name: 'See all 2' }).click();
  await page.evaluate(snapshot => window.render(snapshot), snapshot);
  assert.equal(await overdue.getByRole('button').getAttribute('aria-expanded'), 'true');
  await page.clock.fastForward(14 * 3600000);
  await overdue.locator('[data-id="today-task"]').waitFor();
  assert.equal(await overdue.getByRole('button').getAttribute('aria-expanded'), 'true');
  await page.evaluate(() => { window.clockClears = 0; const clear = window.clearTimeout; window.clearTimeout = id => { window.clockClears++; clear(id); }; window.dispose(); });
  assert.ok(await page.evaluate(() => window.clockClears > 0 && document.getElementById('root').childElementCount === 0));
  await page.clock.fastForward(120000);
  assert.equal(await page.locator('section').count(), 0);
});
for (const timezoneId of ['UTC', 'Pacific/Kiritimati', 'America/Los_Angeles']) for (const midnight of ['2026-03-08T06:00:00Z', '2026-11-01T05:00:00Z']) test(`Central rollover ${midnight} in ${timezoneId}`, async t => {
  const server = await fixtureServer({ root }); t.after(() => server.close());
  const browser = await chromium.launch(); t.after(() => browser.close());
  const page = await browser.newPage({ timezoneId });
  const at = new Date(midnight), today = new Date(at.getTime() - 86400000).toISOString().slice(0, 10);
  await page.clock.install({ time: new Date(at.getTime() - 1000) });
  await page.goto(`${server.origin}/overdue-test.html`); await page.waitForFunction(() => window.render);
  const snapshot = overdueFixture(); snapshot.items = [snapshot.items[0]]; snapshot.items[0].due_on = today;
  await page.evaluate(snapshot => window.render(snapshot), snapshot);
  await page.getByRole('region', { name: 'Today', exact: true }).locator('[data-id]').waitFor();
  await page.clock.runFor(1000);
  await page.getByRole('region', { name: 'Overdue', exact: true }).locator('[data-id]').waitFor();
  assert.equal(await page.getByRole('region', { name: 'Today', exact: true }).locator('[data-id]').count(), 0);
  await page.clock.runFor(4 * 3600000);
  assert.equal(await page.getByRole('region', { name: 'Overdue', exact: true }).locator('[data-id]').count(), 1);
});
